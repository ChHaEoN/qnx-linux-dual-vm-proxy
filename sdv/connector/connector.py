# --- the log ----------------------------------------------------------------------------------------

def _emit(out: Any, t: float, event: str, **fields: Any) -> None:
    """One line of the log."""
    record: Dict[str, Any] = {"event": event, "t": t}
    record.update(fields)
    out.write(json.dumps(record, sort_keys=True, separators=(",", ":")) + "\n")
    flush = getattr(out, "flush", None)
    if flush is not None:
        flush()


def _error_fields(exc: BaseException) -> Dict[str, Any]:
    """What the log says of an error nobody expected: its class, and file and line of each frame it passed through.
    Never its text, and never a traceback, which would print that text."""
    frames = traceback.extract_tb(exc.__traceback__)
    return {"error": type(exc).__name__, "where": ["%s:%d" % (os.path.basename(f.filename), f.lineno or 0) for f in frames]}


def _own_interrupt(exc: BaseException) -> bool:
    """Whether `exc` is to be passed on and not logged: a KeyboardInterrupt with no argument, which is what the
    interpreter raises for a SIGINT while the connector's own handler is not installed. It carries no text. Every
    other error, of whatever class and whoever raised it, ends as a log line and a status."""
    return isinstance(exc, KeyboardInterrupt) and not exc.args


# --- clocks -----------------------------------------------------------------------------------------

class SystemClock:
    """The host's clocks: monotonic time for every interval, wall time for a sample's Linux-host milliseconds."""

    def monotonic(self) -> float:
        return time.monotonic()

    def wall_ms(self) -> int:
        return time.time_ns() // 1_000_000

    def sleep(self, seconds: float) -> None:
        if seconds > 0:
            time.sleep(seconds)


class ManualClock:
    """A clock a test moves, kept in whole milliseconds. sleep() advances it and then calls each hook in on_sleep
    with the clock, which is where a test puts what happens meanwhile."""

    def __init__(self, t: float = 0.0, wall_ms: int = 0) -> None:
        self._ms = int(round(t * 1000))
        self._wall0 = int(wall_ms) - self._ms
        self.on_sleep: List[Callable[["ManualClock"], Any]] = []

    def monotonic(self) -> float:
        return self._ms / 1000.0

    def wall_ms(self) -> int:
        return self._wall0 + self._ms

    def advance(self, seconds: float) -> None:
        self._ms += int(round(seconds * 1000))

    def sleep(self, seconds: float) -> None:
        self.advance(max(seconds, 0.0))
        for hook in list(self.on_sleep):
            hook(self)


