"""connector.py -- the twin connector's loop and its entry point (sdv/connector; SDV Phase 4 WP2).

Standard library only at import. This file imports no SDK: the entry point asks
uplink_aws.py (WP3, the one SDK importer) for the real uplink, and the frozen allowlist is twin_allowlist.py, baked
into the image beside these modules (generated by gen_allowlist.py; never mounted, never read from a file at run
time).

WHAT IT DOES
  It reads allowlisted VSS paths from the local databroker and sends them up an authenticated uplink: a batch of
  samples to one Basic Ingest topic, the latest values to the `vss` named shadow. From the `config` named shadow it
  takes a rate, a narrowing of the path set, and two requests it hands on through the spool file; to it it reports the
  rate, the path set and the updater's status record. It starts and stops no container and reads no log, record
  directory or lock: its inputs are the databroker, the uplink and the status record (status.py, read only), its only
  files written the spool record and, beside it, the stamp of its own last start.

THE TWO LAYERS OF THE EXCLUSION (design twin-allowlist.md section 6)
  1. It subscribes to the effective set and to nothing else, each path an exact leaf, never a branch (_subscription).
  2. It serialises only values received for those paths (_read keeps nothing else), and AppState only as a record
     that validates (appstate.py).
  The effective set is always a subset of the frozen tuple (pathset.py). Past the frozen tuple there is no second
  list here: whatever that module names goes out, which is why it is generated, checked against a fresh generation
  at the image build, and never mounted.

BEHAVIOUR, in one place (the connector contract; every number is limits.py's and a design value)
  start      first the start stamp (startstamp.py): a start within START_SPACING_S of the previous start on the same
             spool directory is refused, and nothing is opened. The limiter is new in every process; the stamp is
             what holds a restart loop. Then: connect; subscribe to the five reply topics; publish one `config` get.
             Nothing is sampled or sent until the get is answered (accepted, or rejected because no shadow exists
             yet) or CONFIG_GET_WAIT_S passed.
  tick       on the connector's own tick (1 Hz, or 10 Hz when `config` asks; no other rate) take the latest value of
             each effective path, add one row to the open batch (no row when no path has a value), and keep the
             latest valid AppState record of each app.
  batch      closed every 60 s at 1 Hz and every 10 s at 10 Hz and published; an empty batch is not sent. A change
             of the effective path set or of the rate closes and sends the open batch first, then starts a new one,
             so no batch mixes two row shapes.
  vss        the reported document goes when a value other than AppState's seq changed, no closer than 60 s to the
             previous one, and once at stop. Every document carries every allowlisted key, null where the path is
             narrowed out or has no value (shadowdoc.py). The first one waits for the source's first value,
             FIRST_DOCUMENT_WAIT_S at most.
  config     read once per connection (the get), then followed by its delta. Reported once per connection, and
             afterwards only when the effective rate, the path set or the status part (below) is not the one last
             reported: a delta repeats every desired attribute that still differs, so a report per delta would loop
             (config.py). A desired image ID or scenario name goes into the spool and nowhere else: not into a
             report, not into the log. The image ID and the scenario a report carries are the status record's.
             A message older than one already applied is not applied. When that message is the get's answer (a
             delta overtook it), the get counts as answered all the same; what the answer said of keys the delta
             did not name is then not taken on this connection.
             "Once" means once it went out: a get or a report that the limiter refused or the uplink failed stays
             due and goes when it may (limits, failed). A spool write that failed is not remembered as written:
             the same request, when the service repeats it, is written then, a second later at the earliest.
  status     the updater's status record, read once a tick from SDV_TWIN_STATUS/status.json (status.py). A valid one
             goes into `config` reported beside the rate and the path set, its three keys as the record has them,
             and a report goes when it changed, under the rules above. Once the shadow shows a status -- this
             process reported one, or a get's answer holds one in reported: an earlier process's (a host's restart
             clears the record, and the updater writes none for a request it already processed) or another host's
             -- a status that is gone or refused is reported as three nulls (the service deletes them) in the next
             report and in every later one, each new connection's first among them, until a valid status is read,
             so the shadow keeps no stale image. A refusal is counted (status_refused) and logged by its reason
             when the reason changes; no value of a status, valid or refused, is logged, and none of a get's answer
             is kept. With no status ever valid and none in the shadow the report is the rate and the path set alone.
  limits     every publish goes through the limiter. What it refuses is dropped and counted, never queued; a shadow
             publish it refused is not tried again before the moment the limiter named.
  failed     a publish the uplink FAILED (it raised: the publish may have gone out or not) is counted, logged by
             the error's class, and never sent again as it was. A telemetry batch is dropped. After a shadow
             publish that failed (the get, a `vss` document, a `config` report) nothing is tried on a shadow topic
             for SHADOW_RETRY_S, the stop's last document alone excepted; then whatever is due goes: the get
             again, the report of the settings then in force, a document of the values then read. So an uplink
             that fails every publish is asked once a spacing on the shadow topics, whatever is due, and its
             failed attempts (which keep their place in the limiter's window) leave the window room for what
             follows. The order in a step is the get, the document, the report, and the first that fails ends
             that step's shadow publishes: a get that alone fails every time keeps the document and the report
             from being tried at all (but the stop's document), a document that alone fails every time the
             report. A report that alone fails every time keeps nothing back; its attempts and the documents
             then share the window's ten, and the limiter may refuse one.
  stop       SIGTERM or SIGINT: one last read of the source, the open batch closed and sent, one last `vss`
             document, then the source and the uplink closed. A stop before the config was read flushes nothing.
             When the limiter refuses that batch for its one-second gap (a telemetry publish went out less than a
             second ago), the stop waits the gap out, once (a second and a millisecond at the most), and sends;
             refused for the window's cap, the batch is dropped and counted like any other.

THE LOG is JSON lines on stdout (LOG_EVENTS). It never holds the endpoint, the thing's or the rule's name, a topic or
a file path, and never a value it was sent or refused: a publish is named by what it is (telemetry, vss, config, get),
an error by its class, an AppState problem by property and keyword, a spool write by which fields it set, a status read
by its reason (and a report by whether it carried a status or cleared one), a refused start by its reason and how long
is left. The start line gives the allowlist's version and digest and the first twelve
digits of the catalogue's sha256 the frozen module was generated from, so that a record names the generation it ran
on; the stop line the counters: the connector's, the limiter's, the source's, and the uplink's own (`uplink`, read
through the limiter as counts and nothing else: connections opened, lost, given up and found without life (`stale`),
and resumed_by_sdk, an SDK that came back by itself, which it does with nothing to send; uplink_aws.py, THE CHOICE, g).

NO ERROR'S TEXT LEAVES THIS PROCESS, as a traceback or as a message, on stdout or on stderr: an error's text can name
the endpoint, the thing, a topic or the key's path (uplink.py lets an UplinkError say anything), and a container's
log is both streams.
  before the loop   main() puts the connector together. What it cannot have (a name, the frozen module, the schema,
                    the uplink module or its settings, the databroker client) ends as status 2 and one line on stderr
                    that was written beforehand and repeats nothing.
  opening           connect and the five subscriptions. An UplinkError there is logged as connect-failed, by its
                    class (status 1). The first get follows them and is a publish like any other: an UplinkError
                    there is publish-failed, the run goes on (with the defaults, once the get's wait is over), and
                    the get is asked again a spacing later (failed, above).
  everywhere        an error of any other class, before the loop, while opening or inside the loop, is the log's
                    error line: its class and where it was raised (file and line of each frame), never its text
                    (status 3). Inside the loop the last flush is still tried, without another read of the source.
                    Any other class: also one that is no Exception, such as a library's SystemExit, whose text
                    Python would print, or a KeyboardInterrupt raised with a text, which it would trace back.
  passed on         one thing: a KeyboardInterrupt that carries no argument. That is what the interpreter itself
                    raises for a SIGINT while the connector's handler is not installed (main() installs it once the
                    connector is put together). It holds no text; Python prints its traceback, which names files
                    and lines of this code and nothing else, and ends the process as an interrupted one.

THE ENVIRONMENT (the device directory's environment file, never the argv)
  SDV_TWIN_THING, SDV_TWIN_RULE   the names the topics are made of (topics.py checks them);
  SDV_TWIN_DATABROKER             the databroker, default 127.0.0.1:55555;
  SDV_TWIN_SPOOL                  the spool directory, default /run/sdv-local/spool/v1 (the start stamp lies there too);
  SDV_TWIN_STATUS                 the status record's directory, default /run/sdv-local/status/v1 (status.py), where the
                                  stack mounts it read-only;
  SDV_TWIN_SCHEMA                 the AppState schema, default appstate.schema.json beside this file.
  Whatever else the uplink needs (the endpoint, the key, the certificate) is uplink_aws.py's to read; this file does
  not look at it.

Exit status: 0 after a stop; 1 when the uplink could not be opened; 2 when the connector could not be put together
(an argument, a setting that is missing or malformed, a part of the build that is absent); 3 when an error nobody
expected ended it; 4 when the start was refused (it came within START_SPACING_S of the previous start on this spool
directory, or the start stamp could not be kept): nothing was opened, and a restart before the time the log names
is refused again.

Does not demonstrate: the service's side of any of it (the tests' fake shadow is our reading of its documentation),
the SDK, the databroker (a fake source in CI), a connector started on another spool directory (the stamp is per
directory: limits.py says who holds what), that the frozen module is the build's own generation (nothing here checks
it against a catalogue: the image build's gen_allowlist.py --check is that gate, WP3), or any timing. Nor what a
real uplink fails, or when: the tests' far end fails on demand, and whether a publish the SDK reports as failed went
out after all is not known here (the limiter counts it as if it had). Nor an error raised on a thread of the uplink's
or of the source's, or a library that raises a KeyboardInterrupt with no text: that one is taken for the
interpreter's own and passed on. Nor that a status record says what runs on the host (it is the updater's own report),
or that the shadow holds no stale image after a connection whose get was never answered: what an earlier process left
in the shadow is learnt from a get's answer and from nothing else.
"""
