class Connector:
    """One connection's life. Built by build(), on the limiter and on nothing else."""

    def __init__(self, uplink: Any, source: Any, clock: Any, topics: Topics, frozen: Any, schema: Mapping[str, Any],
                 spool_dir: Any, out: Any, *, status_dir: Any) -> None:
        if not isinstance(uplink, Limiter):
            raise TypeError("the connector is built on the limiter and on nothing else (connector.build wraps the uplink)")
        self.uplink = uplink
        self.source = source
        self.clock = clock
        self.topics = topics
        self.frozen = frozen
        self.schema = schema
        self.spool_dir = spool_dir
        self.status_dir = status_dir
        self.out = out
        self.config = config.Config(frozen.PATHS)
        self.counters: Dict[str, int] = dict.fromkeys(COUNTERS, 0)
        self._seq_keys = shadowdoc.seq_keys(frozen)
        self._inbox: Deque[Tuple[str, Any]] = collections.deque(maxlen=limits.INBOX_MAX)
        self._overflowed = 0                 # written by the uplink's thread only
        self._resumed = False                # set by the uplink's thread, taken by step()
        self._stop_requested = False
        self._signal: Optional[int] = None
        self._started = False
        self._stopped = False
        self._ready = False                  # the config get was answered, or its wait is over
        self._get_due = False
        self._t_get = 0.0
        self._version: Optional[int] = None  # the highest `config` shadow version seen on this connection
        self._subscribed: Optional[Tuple[str, ...]] = None
        self._base: Optional[float] = None   # the tick grid's origin
        self._t_ready = 0.0                  # when sampling began
        self._next_tick = 0.0
        self._batch: Optional[_Batch] = None
        self._batch_counter = 0
        self._records: Dict[str, Dict[str, Any]] = {}
        self._appstate_seen: Dict[str, Any] = {}
        self._vss_last: Optional[Dict[str, Any]] = None
        self._vss_t: Optional[float] = None
        self._reported: Optional[Tuple[int, Tuple[str, ...], Optional[Tuple[Optional[str], ...]]]] = None
        self._status: Optional[Tuple[Optional[str], ...]] = None          # the valid status read at the last tick, or None
        self._status_why: Optional[str] = statusrec.MISSING               # why not at the last read: logged when it changes
        self._status_shown = False           # the shadow shows a status: a report of one went out, or a get's answer held one
        #                                      in reported (_shadow_status); from then on, nulls clear it
        self._hold = 0.0                     # no shadow publish is tried before this moment: the limiter named it, or
        #                                      the uplink failed one and this is SHADOW_RETRY_S later (_held)
        self._refusal: Optional[LimitRefused] = None          # the limiter's last refusal, for the stop's one retry
        self._spool_pending: Optional[Dict[str, Optional[str]]] = None
        self._spool_last: Optional[Dict[str, Optional[str]]] = None
        self._spool_t: Optional[float] = None

    # --- what the tests and the entry point read ---

    @property
    def rate_hz(self) -> int:
        return self.config.rate_hz

    @property
    def effective(self) -> Tuple[str, ...]:
        return self.config.paths

    # --- the uplink's side: any thread ---

    def _on_message(self, topic: str, payload: Any) -> None:
        if len(self._inbox) >= limits.INBOX_MAX:
            self._overflowed += 1            # the deque drops its oldest: the newest desired state is the one that counts
        self._inbox.append((topic, payload))

    def _on_resumed(self) -> None:
        self._resumed = True

    def request_stop(self, signum: Optional[int] = None) -> None:
        """Ask the loop to stop after its current step (a signal handler calls this)."""
        self._signal = signum
        self._stop_requested = True

    # --- the loop ---

    def start(self) -> None:
        """Mark the start, connect, subscribe to the reply topics and ask for the config. Raises StartRefused when
        the start comes too soon after the previous one (nothing was opened), UplinkError when connect or a
        subscription fails, and whatever else the uplink raises: run() turns each into a log line and a status. An
        UplinkError at the get is not raised: it is a failed publish, and the get stays due (_get)."""
        startstamp.mark(self.spool_dir, self.clock.wall_ms())
        self._log("start", allowlist_version=self.frozen.VERSION, allowlist_digest="0x%08X" % self.frozen.DIGEST,
                  catalogue=self.frozen.CATALOGUE_SHA256[:12], paths=len(self.frozen.PATHS), rate_hz=self.rate_hz)
        self.uplink.connect(self._on_resumed)
        for topic in self.topics.subscribe:
            self.uplink.subscribe(topic, self._on_message)
        self._started = True
        self._get_due = True
        self._t_get = self.clock.monotonic()
        self._get(self._t_get)

    def step(self, now: Optional[float] = None) -> None:
        """One turn of the loop at `now` (the clock's time when left out): take what arrived, and do what is due."""
        if not self._started or self._stopped:
            return
        if now is None:
            now = self.clock.monotonic()
        if self._resumed:                    # a new connection: read the config again and report once more
            self._resumed = False
            self.counters["resumed"] += 1
            self._version = None             # the shadow may have been made anew meanwhile
            self._reported = None
            self._vss_last = None
            self._get_due = True
        self._get(now)
        self._drain(now)
        self._spool(now)
        if not self._ready:
            if now - self._t_get < limits.CONFIG_GET_WAIT_S - _EPS:
                return
            self._ready = True
            self._log("config-get", outcome="timeout")
        if self._base is None:
            self._base = now
            self._next_tick = now
            self._t_ready = now
        if self._subscribed != self.effective:
            self.source.subscribe(self._subscription())
            self._subscribed = self.effective
            self.counters["subscribes"] += 1
        if now + _EPS >= self._next_tick:
            self._tick(now)
        self._report(now)

    def run(self) -> int:
        """Start, step until a stop is requested, flush. 0 after a stop, 1 when the uplink could not be opened, 3 when
        an error nobody expected ended it, while the connection was opened or in the loop (logged by class and place,
        never by its text; of any class, an Exception or not), 4 when the start was refused. No error leaves this
        method but one from the log itself and the interpreter's own interrupt (_own_interrupt)."""
        try:
            self.start()
        except startstamp.StartRefused as refused:
            self._log("start-refused", why=refused.why, retry_after_s=refused.retry_after_s)
            self._stopped = True
            self._close()
            return 4
        except UplinkError as exc:
            self._log("connect-failed", error=type(exc).__name__)
            self._stopped = True
            self._close()
            return 1
        except BaseException as exc:  # noqa: BLE001 -- an SDK's own class, not wrapped, or no Exception at all: no traceback here either
            if _own_interrupt(exc):
                raise
            self._log_error(exc)
            self._stopped = True
            self._close()
            return 3
        status = 0
        try:
            while not self._stop_requested:
                now = self.clock.monotonic()
                self.step(now)
                wake = min(self._next_tick, now + 1.0) if self._base is not None else now + _WAIT_POLL_S
                self.clock.sleep(max(wake - self.clock.monotonic(), _MIN_SLEEP_S))
        except BaseException as exc:  # noqa: BLE001 -- no traceback: an error's text may name the endpoint, a topic or a file
            if _own_interrupt(exc):
                raise
            self._log_error(exc)
            status = 3
        try:
            self.stop(self._signal, read=status == 0)
        except BaseException as exc:  # noqa: BLE001 -- the same, in the last flush
            if _own_interrupt(exc):
                raise
            self._log_error(exc)
            self._stopped = True
            self._close()
            status = 3
        return status

    def stop(self, signum: Optional[int] = None, read: bool = True) -> None:
        """The last flush: one last read of the source, the open batch, one last `vss` document; then everything
        closed. Once. After an unexpected error (`read` false) the source is not read again: the rows already sampled
        go out, and no `vss` document is made of values nobody has."""
        if self._stopped:
            return
        now = self.clock.monotonic()
        if self._started and self._subscribed is not None:
            values: Optional[Dict[str, Any]] = None
            if read:
                values = self._read()
                if self._batch is not None:
                    self._batch.records.update(self._records)
            self._close_batch(now, last=True)
            if values is not None:
                self._vss(self.clock.monotonic(), values, force=True)
        self._stopped = True
        self._close()
        self._log("stop", signal=signum, counters=dict(self.counters), limiter=dict(self.uplink.counters),
                  uplink=self.uplink.below(), source=dict(getattr(self.source, "counters", None) or {}))

    def _close(self) -> None:
        for close in (self.source.close, self.uplink.close):
            try:
                close()
            except Exception:  # noqa: BLE001 -- closing is best effort; the process is ending
                pass

    # --- the source ---

    def _subscription(self) -> Tuple[str, ...]:
        """What the source is asked for: the effective set, each an exact leaf. Never a branch."""
        return self.effective

    def _read(self) -> Dict[str, Any]:
        """The latest value of each effective path, and nothing else the source may have handed over; and each app's
        AppState record when all of its leaves give one that validates."""
        raw = self.source.latest()
        values = {p: raw[p] for p in self.effective if raw.get(p) is not None}
        records: Dict[str, Dict[str, Any]] = {}
        for branch in self.frozen.APPSTATE_BRANCHES:
            leaves = [leaf for leaf in self.frozen.APPSTATE_FIELDS if leaf.rsplit(".", 1)[0] == branch]
            if not any(leaf in values for leaf in leaves):
                self._appstate_seen[branch] = None          # the app is not there, or its leaves are narrowed out: nothing to drop
                continue
            record, problems = appstate.checked(self.schema, self.frozen.APPSTATE_FIELDS, branch, values)
            if record is None:
                self.counters["appstate_dropped"] += 1
            else:
                records[branch] = record
            seen = tuple(problems)
            if self._appstate_seen.get(branch) != seen:          # logged on a change, not on every tick
                self._appstate_seen[branch] = seen
                self._log("appstate", app=branch.rsplit(".", 1)[1], ok=record is not None, reasons=list(problems))
        self._records = records
        return values

    # --- the tick: a sample, the batch, the vss document ---

    def _tick(self, now: float) -> None:
        assert self._base is not None
        k = int(math.floor((now - self._base) * self.rate_hz + _EPS))
        self._next_tick = self._base + (k + 1) / float(self.rate_hz)
        self._read_status()
        values = self._read()
        if self._batch is None:
            self._batch = _Batch(envelope.telemetry_paths(self.frozen, self.effective), now)
        batch = self._batch
        sample = envelope.row(self.clock.wall_ms(), batch.paths, values, self.frozen.NODES)
        if envelope.has_value(sample):
            batch.rows.append(sample)
        batch.records.update(self._records)
        batch.ticks += 1
        if batch.ticks >= limits.batch_ticks(self.rate_hz) or now - batch.t_open >= limits.BATCH_INTERVAL_S[self.rate_hz] - _EPS:
            self._close_batch(now)
        self._vss(now, values, force=False)

    def _close_batch(self, now: float, last: bool = False) -> None:
        """Close the open batch and publish it; an empty one is not sent. What the limiter refuses is dropped; but the
        `last` one, the stop's, when it is refused for the one-second gap, waits that gap out and is sent then."""
        batch, self._batch = self._batch, None
        if batch is None:
            return
        records = [batch.records[b] for b in self.frozen.APPSTATE_BRANCHES if b in batch.records]
        if not batch.rows and not records:
            self.counters["empty_batches"] += 1
            return
        self._batch_counter += 1
        payload = envelope.encode(envelope.batch(self._batch_counter, batch.paths, batch.rows, records))
        outcome = self._publish("telemetry", self.topics.telemetry, payload, now)
        refusal = self._refusal
        if outcome == "refused" and last and refusal is not None and refusal.why == "rate" and refusal.retry_after_s is not None:
            self.clock.sleep(refusal.retry_after_s + _MIN_SLEEP_S)          # 1.001 s at the most; once, and only at the stop
            outcome = self._publish("telemetry", self.topics.telemetry, payload, self.clock.monotonic())
        if outcome == "sent":
            self._log("batch", batch=self._batch_counter, rows=len(batch.rows), bytes=len(payload))

    def _vss(self, now: float, values: Mapping[str, Any], force: bool) -> None:
        """The `vss` reported document, when it is due: something other than seq changed and the previous one is 60 s
        old; or `force`, the one at stop."""
        state = shadowdoc.vss_state(self.frozen, self.effective, values, self._records)
        if not force:
            if self._held(now):
                return
            if self._vss_t is None and not values and now - self._t_ready < limits.FIRST_DOCUMENT_WAIT_S - _EPS:
                return                       # the first document waits a moment for the source's first value
            if self._vss_t is not None and now - self._vss_t < limits.SHADOW_MIN_INTERVAL_S - _EPS:
                return
            if self._vss_last is not None and not shadowdoc.changed(self._vss_last, state, self._seq_keys):
                return
        try:
            payload = shadowdoc.reported(state)
        except shadowdoc.DocRefused:
            self.counters["doc_refused"] += 1
            self._vss_t = now
            return
        outcome = self._publish("vss", self.topics.vss_update, payload, now)
        self._vss_t = now                    # it went, may have gone, or was refused: the next try is 60 s away at the earliest
        if outcome == "sent":
            self._vss_last = state
            self._log("shadow", name="vss", bytes=len(payload), values=len([v for v in state.values() if v is not None]))

    # --- config ---

    def _get(self, now: float) -> None:
        """The `config` get, while one is due: once per connection, and until it went out. One the limiter refused or
        the uplink failed stays due, and is not asked again while shadow publishes are held back."""
        if not self._get_due or self._held(now):
            return
        if self._publish("get", self.topics.config_get, b"", now) == "sent":
            self._get_due = False
            self._t_get = now

    def _drain(self, now: float) -> None:
        if self._overflowed:
            self.counters["inbox_overflow"] = self._overflowed
        while True:
            try:
                topic, payload = self._inbox.popleft()
            except IndexError:
                return
            self._handle(topic, payload, now)

    def _handle(self, topic: str, payload: Any, now: float) -> None:
        t = self.topics
        if topic == t.vss_update_rejected or topic == t.config_update_rejected:
            self.counters["rejected_vss" if topic == t.vss_update_rejected else "rejected_config"] += 1
            return                           # counted; its text is the service's and is not logged. The next document is the retry
        if topic == t.config_get_rejected:
            self.counters["get_rejected"] += 1
            if not self._ready:              # no `config` shadow yet: the defaults
                self._ready = True
                self._log("config-get", outcome="rejected")
            return
        if topic != t.config_get_accepted and topic != t.config_update_delta:
            self.counters["unexpected"] += 1
            return
        doc = config.parse(payload)
        state = doc.get("state") if doc is not None else None
        if doc is None or not isinstance(state, dict):
            self.counters["bad_messages"] += 1
            return
        if topic == t.config_get_accepted and not self._ready:
            self._ready = True               # the get was answered, whatever the answer's version: no wait, no time-out
            self._log("config-get", outcome="accepted")
        if topic == t.config_get_accepted:
            self._shadow_status(state.get("reported"))          # before the version: an answer too old to apply shows it too
        version = config.version_of(doc)
        if version is not None:
            if self._version is not None and version < self._version:
                self.counters["stale"] += 1          # older than what was already applied: a late duplicate, or an
                return                               # answer a delta overtook. Not applied over the newer state
            self._version = version
        if topic == t.config_get_accepted:
            self._apply(state.get("desired", {}), True, now)
        else:
            self.counters["deltas"] += 1
            self._apply(state, False, now)

    def _apply(self, desired: Any, full: bool, now: float) -> None:
        """Take one desired state. Nothing is published here but the batch a change closes: the report follows from
        the effective settings, in _report, and only when they differ from the last one reported."""
        outcome = self.config.apply(desired, full)
        self.counters["ignored"] += outcome.ignored
        if outcome.changed:
            self._close_batch(now)           # the open batch keeps its own header: closed and sent before the change shows
            if outcome.rate_changed and self._base is not None:
                self._base = now
                self._next_tick = now
        if outcome.spool is not None:
            self._spool_pending = outcome.spool

    def _read_status(self) -> None:
        """The updater's status record, once a tick (status.py). A refusal is counted and logged by its reason when the
        reason changes (a run of reads refused for one reason counts once); a record that vanished is logged, not
        counted. No value of what was read is logged, valid or refused."""
        got = statusrec.read(self.status_dir)
        self._status = None if got.record is None else tuple(got.record[key] for key in statusrec.KEYS)
        if got.why != self._status_why:
            self._status_why = got.why
            if got.why is not None and got.why != statusrec.MISSING:
                self.counters["status_refused"] += 1
            self._log("status", ok=got.why is None, why=got.why)

    def _shadow_status(self, reported: Any) -> None:
        """A get's answer: when the shadow's reported state holds a key of the status, the shadow shows a status this process
        may never have read (an earlier process's, from before a host's restart, or another host's), and a report with no
        valid status clears it (_status_part). Taken from every answer, one too old to apply as well: the nulls delete a key
        that is there and change nothing where none is. Nothing of the answer is kept or logged."""
        if isinstance(reported, dict) and any(key in reported for key in statusrec.KEYS):
            self._status_shown = True

    def _status_part(self) -> Optional[Tuple[Optional[str], ...]]:
        """What `config` reported carries of the status: the valid one; else three nulls once the shadow shows a status
        (this process reported one, or a get's answer held one: the service deletes a key reported as null, so the shadow
        never shows a stale image); else nothing."""
        if self._status is not None:
            return self._status
        return _NULLS if self._status_shown else None

    def _report(self, now: float) -> None:
        """`config` reported: once per connection, then only when the effective rate, the path set or the status part
        changed. A report the limiter refused for its window or the uplink failed stays due: it is made anew, from the
        settings and the status then in force, when shadow publishes are no longer held back."""
        part = self._status_part()
        current = (self.rate_hz, self.effective, part)
        if current == self._reported or self._held(now):
            return
        status = None if part is None else dict(zip(statusrec.KEYS, part))
        try:
            payload = shadowdoc.reported(shadowdoc.config_state(self.rate_hz, self.effective, status))
        except shadowdoc.DocRefused:
            self.counters["doc_refused"] += 1
            self._reported = current
            return
        outcome = self._publish("config", self.topics.config_update, payload, now)
        if outcome == "sent":
            self._reported = current
            fields: Dict[str, Any] = {}
            if part is not None:
                self._status_shown = True
                fields["status"] = "cleared" if part == _NULLS else "reported"
            self._log("config", rate_hz=self.rate_hz, paths=len(self.effective), **fields)
        elif outcome == "refused" and now >= self._hold:
            self._reported = current         # refused, and waiting does not help (its size): not tried again as it is

    def _spool(self, now: float) -> None:
        """Write the requested image ID and scenario into the spool: at most one try a second, the last request wins,
        and a request equal to the last one WRITTEN is not written again. A write that failed is counted and logged,
        and is not remembered as written: nothing tries it again by itself, but the same request, when it comes again
        (the service repeats it in every delta), is written then."""
        record = self._spool_pending
        if record is None:
            return
        if record == self._spool_last:
            self._spool_pending = None
            return
        if self._spool_t is not None and now - self._spool_t < limits.SPOOL_MIN_GAP_S - _EPS:
            return
        self._spool_pending, self._spool_t = None, now
        fields = {name: record[name] is not None for name in spool.FIELDS}          # which fields, never what
        try:
            spool.write(self.spool_dir, record)
        except (OSError, spool.SpoolRefused) as exc:
            self.counters["spool_failed"] += 1
            self._log("spool", ok=False, error=type(exc).__name__, **fields)
            return
        self._spool_last = record            # only now: a request whose write failed is still to be written
        self.counters["spool_written"] += 1
        self._log("spool", ok=True, **fields)

    # --- the wire and the log ---

    def _held(self, now: float) -> bool:
        """Whether shadow publishes are held back at `now`: the limiter refused one and named a later moment, or the
        uplink failed one less than SHADOW_RETRY_S ago. (Two readings of the clock _EPS apart are the same moment.)"""
        return now + _EPS < self._hold

    def _publish(self, what: str, topic: str, payload: bytes, now: float) -> str:
        """One publish through the limiter: sent, refused (by the limiter: dropped and counted) or failed (by the
        uplink: counted and logged by its class, never its text). A shadow publish that was refused or that failed
        holds every shadow publish back for a while (_held); a telemetry publish holds nothing back."""
        self._refusal = None
        try:
            self.uplink.publish(topic, payload, limits.QOS)
        except LimitRefused as exc:
            self._refusal = exc
            self.counters["refused_" + what] += 1
            if what != "telemetry" and exc.retry_after_s is not None:
                self._hold = now + exc.retry_after_s
            return "refused"
        except UplinkError as exc:
            self.counters["failed_" + what] += 1
            self._log("publish-failed", what=what, error=type(exc).__name__)
            if what != "telemetry":          # it may have gone out, and the limiter counted it: no attempt a step
                self._hold = max(self._hold, now + limits.SHADOW_RETRY_S)
            return "failed"
        self.counters["sent_" + what] += 1
        return "sent"

    def _log_error(self, exc: BaseException) -> None:
        self._log("error", **_error_fields(exc))

    def _log(self, event: str, **fields: Any) -> None:
        _emit(self.out, self.clock.monotonic(), event, **fields)


# --- the entry point --------------------------------------------------------------------------------

def build(uplink: Any, source: Any, clock: Any, topics: Topics, frozen: Any, schema: Mapping[str, Any], spool_dir: Any,
          out: Any, *, status_dir: Any) -> Connector:
    """The connector on `uplink`, with the limiter in between: the one place a connector is made. `status_dir` is where
    the updater's status record is read (status.py)."""
    return Connector(Limiter(uplink, topics, clock), source, clock, topics, frozen, schema, spool_dir, out, status_dir=status_dir)


def _sdk_uplink(env: Mapping[str, str], topics: Topics) -> Any:
    import uplink_aws
    return uplink_aws.from_env(env, topics)


def _kuksa_source(target: str) -> Any:
    return sources.KuksaSource(sources.GrpcStream(target))


# Why the connector cannot be put together: status 2 and one of these sentences on stderr. Each was written here,
# beforehand; none repeats a value, a path or another error's text.
REFUSALS = {
    "argument": "it takes no argument; its settings come from the environment",
    "names": "%s and %s must name the thing and the rule (the device directory's environment file); one of them is "
             "missing or malformed" % (ENV_THING, ENV_RULE),
    "allowlist": "this build holds no frozen allowlist that imports (twin_allowlist.py)",
    "schema": "the AppState schema cannot be read or is no schema (%s; by default appstate.schema.json beside the "
              "connector)" % ENV_SCHEMA,
    "sdk": "this build holds no SDK uplink (uplink_aws.py, or the SDK it imports)",
    "uplink": "the uplink cannot be set up from its settings (the device directory's environment file)",
    "databroker": "this build holds no databroker client (grpc and kuksa-client)",
}


class _Refused(Exception):
    """The connector cannot be put together: `why` is a key of REFUSALS, and only that table's sentence is printed."""

    def __init__(self, why: str) -> None:
        super().__init__(why)
        self.why = why


def _assemble(env: Mapping[str, str], make_uplink: Optional[Callable[[Mapping[str, str], Topics], Any]],
              make_source: Optional[Callable[[str], Any]], clock: Any, out: Any, frozen: Any) -> Connector:
    """The connector from its settings, or _Refused. Each part's own error ends here, and its text with it."""
    try:
        topics = Topics(env.get(ENV_THING), env.get(ENV_RULE))
    except TopicsError:
        raise _Refused("names") from None
    if frozen is None:
        try:
            import twin_allowlist
        except Exception:  # noqa: BLE001 -- absent, or refusing to import: its own check raises with a text
            raise _Refused("allowlist") from None
        frozen = twin_allowlist
    try:
        schema = appstate.load_schema(env.get(ENV_SCHEMA) or str(HERE / "appstate.schema.json"))
    except (OSError, ValueError):
        schema = None
    if not isinstance(schema, dict) or not {"properties", "propertyNames", "required"} <= set(schema):
        raise _Refused("schema")
    try:
        uplink = (make_uplink or _sdk_uplink)(env, topics)
    except ImportError:
        raise _Refused("sdk") from None
    except UplinkError:          # its text may name the endpoint, the thing or the key's path: uplink.py allows it to
        raise _Refused("uplink") from None
    try:
        source = (make_source or _kuksa_source)(env.get(ENV_DATABROKER) or DEFAULT_DATABROKER)
    except ImportError:
        raise _Refused("databroker") from None
    return build(uplink, source, clock, topics, frozen, schema, env.get(ENV_SPOOL) or DEFAULT_SPOOL, out,
                 status_dir=env.get(ENV_STATUS) or DEFAULT_STATUS)


def main(argv: Optional[Sequence[str]] = None, env: Optional[Mapping[str, str]] = None,
         make_uplink: Optional[Callable[[Mapping[str, str], Topics], Any]] = None,
         make_source: Optional[Callable[[str], Any]] = None, clock: Any = None, out: Any = None, frozen: Any = None) -> int:
    """Run one connector until SIGTERM or SIGINT. The factories, the clock, the log stream and the frozen module are
    arguments so that a test runs this very function on fakes; left out, they are the SDK uplink, the kuksa source,
    the system clock, stdout and twin_allowlist. No error leaves it, of whatever class, but the interpreter's own
    interrupt, which carries no text (the module's docstring says why, and _own_interrupt which one that is)."""
    args = list(sys.argv[1:] if argv is None else argv)
    if env is None:
        env = os.environ
    if clock is None:
        clock = SystemClock()
    if out is None:
        out = sys.stdout
    previous: Dict[int, Any] = {}
    try:
        if args:
            raise _Refused("argument")
        conn = _assemble(env, make_uplink, make_source, clock, out, frozen)
        for signum in (signal.SIGTERM, signal.SIGINT):
            previous[signum] = signal.signal(signum, lambda received, _frame: conn.request_stop(received))
        return conn.run()
    except _Refused as refused:
        print("connector: %s" % REFUSALS.get(refused.why, "it cannot be put together"), file=sys.stderr)
        return 2
    except BaseException as exc:  # noqa: BLE001 -- by class and place, never by its text; an Exception or not (a library's SystemExit)
        if _own_interrupt(exc):
            raise          # the interpreter's own, for a SIGINT that came before the handlers above were installed: no text in it
        try:
            _emit(out, clock.monotonic(), "error", **_error_fields(exc))
        except Exception:  # noqa: BLE001 -- the log itself cannot be written: one fixed line, and that is all
            print("connector: an error nobody expected, and the log cannot be written", file=sys.stderr)
        return 3
    finally:
        for number, handler in previous.items():
            if handler is not None:
                signal.signal(number, handler)


if __name__ == "__main__":
    sys.exit(main())
